import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { catalog } from './roadmap-helpers';

test.use({ trace: 'off', screenshot: 'off' });
test.afterEach(async ({ page }) => { await page.goto('about:blank'); });

test('version policy blocks an existing old client heartbeat and permits a supported version', async ({ page }) => {
  const { app, issuance } = await catalog(page, 1);
  const deviceId = randomUUID();
  const activation = await page.request.post('/api/client/licenses/activate', { data: { appCode: app.code, licenseKey: issuance.licenses[0].key, deviceId, clientVersion: '2.0.9' } });
  expect(activation.status()).toBe(200);
  const grant = await activation.json();
  await page.goto('/client-policies');
  await expect(page.getByRole('heading', { name: '客户端版本', exact: true })).toBeVisible();
  await page.getByLabel('版本策略应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await page.getByLabel('最低支持版本', { exact: true }).fill('2.1.0');
  await page.getByLabel('最新版本', { exact: true }).fill('2.10.0');
  const enforce = page.getByRole('switch', { name: '强制最低版本', exact: true });
  if (await enforce.getAttribute('aria-checked') !== 'true') await enforce.click();
  await page.getByLabel('更新地址', { exact: true }).fill('https://downloads.example.com/client');
  await page.getByLabel('发布说明', { exact: true }).fill('修复兼容性问题，请升级至新版本。');
  await page.getByRole('button', { name: '保存版本策略', exact: true }).click();
  await expect(page.getByText('版本策略已保存', { exact: true })).toBeVisible();
  const heartbeat = await page.request.post('/api/client/sessions/heartbeat', { headers: { Authorization: `Bearer ${grant.sessionToken}` } });
  expect(heartbeat.status()).toBe(426);
  const supported = await page.request.post('/api/client/licenses/activate', { data: { appCode: app.code, licenseKey: issuance.licenses[0].key, deviceId, clientVersion: '2.1.0' } });
  expect(supported.status()).toBe(200);
  await page.reload();
  await page.getByLabel('版本策略应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await expect(page.getByLabel('最低支持版本', { exact: true })).toHaveValue('2.1.0');
  await expect(page.getByLabel('最新版本', { exact: true })).toHaveValue('2.10.0');
  await page.goto('/audit');
  await page.getByLabel('操作对象 ID', { exact: true }).fill(app.id);
  await page.getByRole('button', { name: '筛选操作对象', exact: true }).click();
  const change = page.getByRole('row').filter({ hasText: '配置客户端版本' });
  await expect(change).toContainText(app.name);
  await expect(change).toContainText('2.1.0');
});

test('offline authorization can be signed, downloaded once and revoked from its record', async ({ page }) => {
  const { app, issuance } = await catalog(page, 1);
  const card = issuance.licenses[0];
  const deviceId = randomUUID();
  expect((await page.request.post('/api/client/licenses/activate', { data: { appCode: app.code, licenseKey: card.key, deviceId } })).status()).toBe(200);
  const detail = await (await page.request.get(`/api/admin/licenses/${card.id}`)).json();
  await page.goto('/offline-licenses');
  await expect(page.getByRole('heading', { name: '离线授权', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '签发离线授权', exact: true }).click();
  const sign = page.getByRole('dialog', { name: '签发离线授权', exact: true });
  await sign.getByLabel('授权 ID', { exact: true }).fill(card.id);
  await sign.getByLabel('绑定 ID', { exact: true }).fill(detail.bindings[0].id);
  await sign.getByLabel('原始设备标识', { exact: true }).fill(deviceId);
  await sign.getByLabel('有效小时', { exact: true }).fill('1');
  await sign.getByRole('button', { name: '确认签发', exact: true }).click();
  await expect(sign).toBeHidden();
  const secret = page.getByRole('dialog', { name: '保存离线许可证', exact: true });
  await expect(secret).toBeVisible();
  const content = await secret.getByTestId('one-time-secret').innerText();
  expect(content.split('.').length === 3).toBe(true);
  const download = page.waitForEvent('download');
  await secret.getByRole('button', { name: '下载保存', exact: true }).click();
  const artifact = await download;
  expect(artifact.suggestedFilename().endsWith('.kglicense')).toBe(true);
  expect((await readFile((await artifact.path())!, 'utf8')) === content).toBe(true);
  const verified = await page.request.post('/api/client/offline-licenses/verify', { data: { licenseContent: content, appCode: app.code, deviceId } });
  expect(verified.status()).toBe(200);
  expect((await verified.json()).licenseId).toBe(card.id);
  await secret.getByRole('button', { name: '已保存，关闭', exact: true }).click();
  await expect(page.getByTestId('one-time-secret')).toHaveCount(0);
  await page.getByLabel('离线授权应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: card.id }).first();
  await row.getByRole('button', { name: '撤销', exact: true }).click();
  await page.getByRole('button', { name: '确认撤销', exact: true }).click();
  await expect(row).toContainText('已撤销');
  const rejected = await page.request.post('/api/client/offline-licenses/verify', { data: { licenseContent: content, appCode: app.code, deviceId } });
  expect(rejected.ok()).toBe(false);
  expect((await rejected.json()).code).toBe('OFFLINE_LICENSE_REVOKED');
  const records = await (await page.request.get('/api/admin/offline-licenses?licenseId=' + card.id)).json();
  await page.goto('/audit');
  await page.getByLabel('操作对象 ID', { exact: true }).fill(records.items[0].id);
  await page.getByRole('button', { name: '筛选操作对象', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: '签发离线授权' })).toContainText(card.keyHint);
  await expect(page.getByRole('row').filter({ hasText: '撤销离线授权' })).toContainText('已撤销');
});

test('version and offline signing drafts survive switching workspace tabs', async ({ page }) => {
  const { app, issuance } = await catalog(page, 1);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/applications');
  await page.getByRole('menuitem', { name: '客户端版本', exact: true }).click();
  await page.getByLabel('版本策略应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await page.getByLabel('最低支持版本', { exact: true }).fill('3.2.1');
  await page.getByLabel('发布说明', { exact: true }).fill('保留尚未发布的说明');
  await page.goBack();
  const tabs = page.getByRole('tablist', { name: '工作区标签', exact: true });
  await tabs.getByRole('tab', { name: '客户端版本', exact: true }).click();
  await expect(page.getByLabel('最低支持版本', { exact: true })).toHaveValue('3.2.1');
  await expect(page.getByLabel('发布说明', { exact: true })).toHaveValue('保留尚未发布的说明');
  await page.getByRole('menuitem', { name: '离线授权', exact: true }).click();
  await page.getByRole('button', { name: '签发离线授权', exact: true }).click();
  const sign = page.getByRole('dialog', { name: '签发离线授权', exact: true });
  await sign.getByLabel('授权 ID', { exact: true }).fill(issuance.licenses[0].id);
  await sign.getByLabel('原始设备标识', { exact: true }).fill('local-draft-device');
  await sign.getByLabel('有效小时', { exact: true }).fill('7');
  await page.goBack();
  await expect(sign).toBeHidden();
  await tabs.getByRole('tab', { name: '离线授权', exact: true }).click();
  await expect(sign).toBeVisible();
  await expect(sign.getByLabel('授权 ID', { exact: true })).toHaveValue(issuance.licenses[0].id);
  await expect(sign.getByLabel('原始设备标识', { exact: true })).toHaveValue('local-draft-device');
  await expect(sign.getByLabel('有效小时', { exact: true })).toHaveValue('7');
  await page.goBack();
  await expect(sign).toBeHidden();
  await page.getByRole('button', { name: '关闭离线授权标签', exact: true }).click();
  await page.getByRole('menuitem', { name: '离线授权', exact: true }).click();
  await expect(sign).toHaveCount(0);
  await page.getByRole('button', { name: '签发离线授权', exact: true }).click();
  await expect(sign.getByLabel('原始设备标识', { exact: true })).toHaveValue('');
  await expect(sign.getByLabel('有效小时', { exact: true })).toHaveValue('24');
  expect(errors).toEqual([]);
});
