import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { catalog, login } from './roadmap-helpers';

test.use({ trace: 'off', screenshot: 'off' });
test.afterEach(async ({ page }) => { await page.goto('about:blank'); });

test('role management creates explicit grants and accounts receive multiple roles', async ({ page }) => {
  const headers = await login(page);
  const roleName = `浏览器角色-${randomUUID().slice(0, 8)}`;
  await page.goto('/roles');
  await expect(page.getByRole('heading', { name: '角色管理', exact: true })).toBeVisible();
  const permissions = await (await page.request.get('/api/admin/permissions')).json();
  const readLabel = permissions.find((item: { code: string }) => item.code === 'licenses.read').label;
  await page.getByRole('button', { name: '创建角色', exact: true }).click();
  const roleDialog = page.getByRole('dialog', { name: '创建角色', exact: true });
  await roleDialog.getByLabel('角色名称', { exact: true }).fill(roleName);
  await roleDialog.getByLabel('角色说明', { exact: true }).fill('手动分配权限的浏览器验收角色');
  await roleDialog.getByRole('checkbox', { name: readLabel, exact: true }).check();
  await roleDialog.getByRole('button', { name: '保存角色', exact: true }).click();
  await expect(roleDialog).toBeHidden();
  const roles = await (await page.request.get(`/api/admin/roles?search=${encodeURIComponent(roleName)}`)).json();
  expect(roles.items[0].permissions).toEqual(['licenses.read']);
  const reportRoleResponse = await page.request.post('/api/admin/roles', { headers, data: { name: `报表角色-${randomUUID().slice(0, 8)}`, permissions: ['reports.read'] } });
  expect(reportRoleResponse.status()).toBe(201);
  const reportRole = await reportRoleResponse.json();
  await page.goto('/accounts');
  await page.getByRole('button', { name: '创建账号', exact: true }).click();
  const accountDialog = page.getByRole('dialog', { name: '创建账号', exact: true });
  const userName = `rbac-${randomUUID().slice(0, 8)}`;
  await accountDialog.getByLabel('用户名', { exact: true }).fill(userName);
  await accountDialog.getByLabel('初始密码', { exact: true }).fill(`${randomUUID()}Aa1!`);
  const rolesInput = accountDialog.getByLabel('账号角色', { exact: true });
  await rolesInput.fill(roleName);
  await page.getByTitle(roleName, { exact: true }).click();
  await rolesInput.fill(reportRole.name);
  await page.getByTitle(reportRole.name, { exact: true }).click();
  await accountDialog.getByRole('button', { name: '创建账号', exact: true }).click();
  await expect(accountDialog).toBeHidden();
  const accounts = await (await page.request.get(`/api/admin/accounts?search=${userName}`)).json();
  expect(accounts.items[0].roleIds.sort()).toEqual([roles.items[0].id, reportRole.id].sort());
  const access = await (await page.request.get(`/api/admin/accounts/${accounts.items[0].id}/access`)).json();
  expect(access.permissions.sort()).toEqual(['licenses.read', 'reports.read']);
  await page.getByRole('row').filter({ hasText: userName }).getByRole('button', { name: '数据范围', exact: true }).click();
  const scope = page.getByRole('dialog', { name: '应用与渠道范围', exact: true });
  await expect(scope.getByRole('checkbox')).toHaveCount(0);
  await expect(scope.getByText('操作权限由已分配角色决定。', { exact: true })).toBeVisible();
});

test('separate logs explain the operator, named object, actual changes and login outcome', async ({ page }) => {
  const { headers, app, plan } = await catalog(page);
  const update = await page.request.patch(`/api/admin/plans/${plan.id}`, { headers, data: { name: `${plan.name}-调整`, durationSeconds: 172800, maxDevices: 2, maxConcurrentSessions: 1, features: [], isEnabled: true } });
  expect(update.ok()).toBe(true);
  await page.goto('/audit');
  await expect(page.getByRole('heading', { name: '操作日志', exact: true })).toBeVisible();
  await page.getByLabel('操作对象 ID', { exact: true }).fill(plan.id);
  await page.getByRole('button', { name: '筛选操作对象', exact: true }).click();
  const updated = page.getByRole('row').filter({ hasText: '修改卡种' }).first();
  await expect(updated).toContainText(process.env.E2E_ADMIN_USER!);
  await expect(updated).toContainText(plan.name);
  await expect(updated).toContainText('成功');
  await expect(updated).not.toContainText(plan.id);
  await updated.getByRole('button', { name: '查看详情', exact: true }).click();
  const detail = page.getByRole('dialog', { name: '操作详情', exact: true });
  await expect(detail.getByRole('columnheader', { name: '修改前', exact: true })).toBeVisible();
  await expect(detail.getByRole('columnheader', { name: '修改后', exact: true })).toBeVisible();
  await expect(detail).toContainText('设备上限');
  await expect(detail).toContainText('平台级操作');
  await expect(detail).not.toContainText(app.name);
  const planAudits = await (await page.request.get('/api/admin/audit-logs?targetId=' + plan.id)).json();
  const globalUpdate = planAudits.items.find((item: { action: string }) => item.action === 'plan.update');
  expect(globalUpdate.applicationId).toBeNull();
  await detail.getByRole('button', { name: '关闭', exact: true }).click();
  await page.goto('/login-logs');
  await expect(page.getByRole('heading', { name: '登录日志', exact: true })).toBeVisible();
  await expect(page.getByRole('columnheader', { name: '登录方式', exact: true })).toBeVisible();
  await expect(page.getByRole('columnheader', { name: '来源 IP', exact: true })).toBeVisible();
  const loginEvents = await (await page.request.get('/api/admin/login-logs')).json();
  expect(loginEvents.items.length).toBeGreaterThan(0);
  expect(loginEvents.items.every((item: { category: string }) => item.category === 'login')).toBe(true);
  await expect(page.getByRole('cell', { name: '修改卡种', exact: true })).toHaveCount(0);
});
