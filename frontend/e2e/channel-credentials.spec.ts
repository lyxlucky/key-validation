import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { catalog } from './roadmap-helpers';

test.use({ trace: 'off', screenshot: 'off' });
test.afterEach(async ({ page }) => { if (!page.isClosed()) await page.goto('about:blank'); });

test('channel configuration persists its quota ledger and plan price', async ({ page }) => {
  const { app, plan, headers } = await catalog(page, 1);
  const suffix = randomUUID().slice(0, 8);
  const userName = `channel-${suffix}`;
  expect((await page.request.post('/api/admin/accounts', { headers, data: { userName, password: `Channel-${randomUUID()}!aA`, role: 'Operator' } })).status()).toBe(201);
  await page.goto('/channels');
  await expect(page.getByRole('heading', { name: '渠道管理', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新建渠道', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '新建渠道', exact: true });
  const name = `渠道验收-${suffix}`;
  await editor.getByLabel('渠道名称', { exact: true }).fill(name);
  await editor.getByLabel('渠道账号', { exact: true }).fill(userName);
  await page.getByTitle(userName, { exact: true }).click();
  await editor.getByLabel('授权应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await editor.getByLabel('授权应用', { exact: true }).press('Escape');
  await editor.getByLabel('初始额度', { exact: true }).fill('3');
  await editor.getByRole('button', { name: '保存渠道', exact: true }).click();
  await expect(editor).toBeHidden();
  await page.getByLabel('搜索渠道', { exact: true }).fill(name);
  const row = page.getByRole('row').filter({ hasText: name });
  await row.getByRole('button', { name: '详情', exact: true }).click();
  const detail = page.getByRole('dialog', { name: '渠道详情', exact: true });
  await detail.getByRole('button', { name: '调整额度', exact: true }).click();
  const quota = page.getByRole('dialog', { name: '调整渠道额度', exact: true });
  await quota.getByLabel('调整数量', { exact: true }).fill('2');
  await quota.getByLabel('调整原因', { exact: true }).fill('已核对人工配额');
  await quota.getByRole('button', { name: '确认调整', exact: true }).click();
  await expect(quota).toBeHidden();
  await expect(detail.getByTestId('channel-remaining-quota')).toHaveText('5');
  await expect(detail.getByRole('row').filter({ hasText: '已核对人工配额' })).toBeVisible();
  await detail.getByRole('button', { name: '设置售价', exact: true }).click();
  const price = page.getByRole('dialog', { name: '设置渠道售价', exact: true });
  await price.getByLabel('定价卡种', { exact: true }).click();
  await page.getByTitle(plan.name, { exact: true }).click();
  await price.getByLabel('售价（分）', { exact: true }).fill('1200');
  await price.getByRole('button', { name: '保存售价', exact: true }).click();
  await expect(price).toBeHidden();
  await expect(detail.getByRole('row').filter({ hasText: plan.name })).toContainText('12.00');
  await page.reload();
  await page.getByLabel('搜索渠道', { exact: true }).fill(name);
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '详情', exact: true }).click();
  await expect(detail.getByTestId('channel-remaining-quota')).toHaveText('5');
  await expect(detail.getByRole('row').filter({ hasText: plan.name })).toContainText('12.00');
});

test('API credential can read its application and rotation immediately invalidates its prior secret', async ({ page }) => {
  const { app } = await catalog(page, 1);
  const name = `接口验收-${randomUUID().slice(0, 8)}`;
  await page.goto('/integrations');
  await page.getByRole('tab', { name: 'API 凭证', exact: true }).click();
  await page.getByLabel('凭证应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await page.getByRole('button', { name: '创建凭证', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '创建 API 凭证', exact: true });
  await editor.getByLabel('凭证名称', { exact: true }).fill(name);
  await editor.getByLabel('凭证应用', { exact: true }).fill(app.name);
  await page.locator('.ant-select-dropdown:has(#api-credential_applicationId_list)').getByTitle(app.name, { exact: true }).click();
  await editor.getByRole('checkbox', { name: '读取授权', exact: true }).check();
  await editor.getByRole('button', { name: '保存凭证', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '保存 API 凭证', exact: true });
  await expect(dialog).toBeVisible();
  const original = (await dialog.getByTestId('one-time-secret').textContent())!;
  await dialog.getByRole('button', { name: '已保存，关闭', exact: true }).click();
  const response = await page.request.get('/api/v1/licenses', { headers: { Authorization: `Bearer ${original}` } });
  expect(response.status()).toBe(200);
  expect((await response.json()).total).toBe(1);
  const row = page.getByRole('row').filter({ hasText: name });
  await row.getByRole('button', { name: '轮换凭证', exact: true }).click();
  await page.getByRole('button', { name: '确认轮换', exact: true }).click();
  await expect(dialog).toBeVisible();
  const rotated = (await dialog.getByTestId('one-time-secret').textContent())!;
  expect(rotated !== original).toBe(true);
  await dialog.getByRole('button', { name: '已保存，关闭', exact: true }).click();
  expect((await page.request.get('/api/v1/licenses', { headers: { Authorization: `Bearer ${original}` } })).status()).toBe(401);
  expect((await page.request.get('/api/v1/licenses', { headers: { Authorization: `Bearer ${rotated}` } })).status()).toBe(200);
  expect((await page.locator('body').textContent())!.includes(rotated)).toBe(false);
});

test('a channel account can have its application scope narrowed without changing its channel', async ({ page }) => {
  const { app, headers } = await catalog(page, 1);
  const suffix = randomUUID().slice(0, 8);
  const userName = `channel-scope-${suffix}`;
  const accountResponse = await page.request.post('/api/admin/accounts', { headers, data: { userName, password: `${randomUUID()}aA1!`, role: 'Operator' } });
  expect(accountResponse.status()).toBe(201);
  const account = await accountResponse.json();
  const channelResponse = await page.request.post('/api/admin/channels', { headers, data: { name: `渠道范围-${suffix}`, accountId: account.id, applicationIds: [app.id], initialQuota: 1 } });
  expect(channelResponse.status()).toBe(201);
  const channel = await channelResponse.json();
  await page.goto('/accounts');
  await page.getByLabel('用户名搜索', { exact: true }).fill(userName);
  await page.getByLabel('用户名搜索', { exact: true }).press('Enter');
  await page.getByRole('row').filter({ hasText: userName }).getByRole('button', { name: '数据范围', exact: true }).click();
  const scope = page.getByRole('dialog', { name: '应用与渠道范围', exact: true });
  await expect(scope.getByText('此账号同时受所属渠道的数据范围限制。', { exact: true })).toBeVisible();
  await scope.getByRole('switch', { name: '全部应用', exact: true }).uncheck();
  await scope.getByLabel('允许访问的应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await scope.getByLabel('允许访问的应用', { exact: true }).press('Escape');
  const saved = page.waitForResponse(response => response.url().endsWith(`/api/admin/accounts/${account.id}/access`) && response.request().method() === 'PUT');
  await scope.getByRole('button', { name: '保存范围', exact: true }).click();
  expect((await saved).status()).toBe(200);
  await expect(scope).toBeHidden();
  const access = await (await page.request.get(`/api/admin/accounts/${account.id}/access`)).json();
  expect(access.channelId).toBe(channel.id);
  expect(access.allApplications).toBe(false);
  expect(access.applicationIds).toEqual([app.id]);
});

test('a credential with no grants can be edited and disabled without adding a permission', async ({ page }) => {
  const { app, headers } = await catalog(page, 1);
  const name = `无权限凭证-${randomUUID().slice(0, 8)}`;
  const created = await page.request.post('/api/admin/api-credentials', { headers, data: { name, applicationId: app.id, channelId: null, permissions: [] } });
  expect(created.status()).toBe(201);
  const { credential } = await created.json();
  await page.goto('/integrations');
  await page.getByRole('tab', { name: 'API 凭证', exact: true }).click();
  await page.getByLabel('凭证应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: name });
  await row.getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '编辑 API 凭证', exact: true });
  await editor.getByRole('switch', { name: '启用凭证', exact: true }).uncheck();
  await editor.getByRole('button', { name: '保存凭证', exact: true }).click();
  await expect(editor).toBeHidden();
  await expect(row).toContainText('未授予操作权限');
  await expect(row).toContainText('已停用');
  const list = await (await page.request.get(`/api/admin/api-credentials?applicationId=${app.id}`)).json();
  const saved = list.items.find((item: { id: string }) => item.id === credential.id);
  expect(saved.permissions).toEqual([]);
  expect(saved.isEnabled).toBe(false);
});
