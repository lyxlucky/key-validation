import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { catalog } from './roadmap-helpers';

test.use({ trace: 'off', screenshot: 'off' });
test.afterEach(async ({ page }) => { if (!page.isClosed()) await page.goto('about:blank'); });

test('manual order delivery reaches the customer portal and a rebinding request is approved once', async ({ page }) => {
  test.setTimeout(150000);
  const { app, plan, headers } = await catalog(page, 1);
  const name = `交付流程-${randomUUID().slice(0, 8)}`;
  await page.goto('/customers');
  await expect(page.getByRole('heading', { name: '客户管理', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新建客户', exact: true }).click();
  const customer = page.getByRole('dialog', { name: '新建客户', exact: true });
  await customer.getByLabel('客户应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await customer.getByLabel('客户名称', { exact: true }).fill(name);
  await customer.getByRole('button', { name: '保存客户', exact: true }).click();
  await expect(customer).toBeHidden();
  await page.getByLabel('搜索客户', { exact: true }).fill(name);
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '访问码', exact: true }).click();
  await page.getByRole('button', { name: '生成新访问码', exact: true }).click();
  const access = page.getByRole('dialog', { name: '保存客户访问码', exact: true });
  await expect(access).toBeVisible();
  const accessCode = (await access.getByTestId('one-time-secret').textContent())!;
  await access.getByRole('button', { name: '已保存，关闭', exact: true }).click();

  await page.goto('/orders');
  await page.getByRole('button', { name: '新建订单', exact: true }).click();
  const order = page.getByRole('dialog', { name: '新建订单', exact: true });
  await order.getByLabel('订单应用', { exact: true }).fill(app.name);
  await page.getByTitle(app.name, { exact: true }).click();
  await order.getByLabel('订单客户', { exact: true }).fill(name);
  await page.getByTitle(name, { exact: true }).click();
  await order.getByLabel('订单卡种', { exact: true }).click();
  await page.getByTitle(plan.name, { exact: true }).click();
  await order.getByLabel('单价（分）', { exact: true }).fill('1000');
  await order.getByRole('button', { name: '保存订单', exact: true }).click();
  await expect(order).toBeHidden();
  const orderRow = page.getByRole('row').filter({ hasText: name }).first();
  await expect(orderRow).toContainText('待履约');
  await orderRow.getByRole('button', { name: '详情', exact: true }).click();
  const detail = page.getByRole('dialog', { name: '订单详情', exact: true });
  await detail.getByRole('button', { name: '确认履约', exact: true }).click();
  await page.getByRole('button', { name: '完成履约', exact: true }).click();
  await expect(detail).toContainText('已履约');
  await detail.getByRole('button', { name: '查看交付', exact: true }).click();
  const delivery = page.getByRole('dialog', { name: '订单交付', exact: true });
  await expect(delivery).toBeVisible();
  const keyElement = delivery.getByTestId('order-delivery-key').first();
  const licenseKey = (await keyElement.textContent())!;
  const licenseId = (await keyElement.getAttribute('data-license-id'))!;
  await delivery.getByRole('button', { name: '关闭交付', exact: true }).click();
  const activated = await page.request.post('/api/client/licenses/activate', { data: { appCode: app.code, licenseKey, deviceId: randomUUID() } });
  expect(activated.status()).toBe(200);
  const grant = await activated.json();
  expect((await page.request.patch(`/api/admin/licenses/${licenseId}/device-policy`, { headers, data: { enabled: true, maxChanges: 2, windowDays: 30, cooldownHours: 0, reason: '配置门户验收换绑规则' } })).ok()).toBe(true);

  await page.goto('/portal');
  await page.getByLabel('客户访问码', { exact: true }).fill(accessCode);
  await page.getByRole('button', { name: '进入自助服务', exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: '已履约' })).toHaveCount(1);
  await page.getByRole('tab', { name: '我的授权', exact: true }).click();
  await page.getByRole('row').filter({ hasText: '有效' }).getByRole('button', { name: '详情', exact: true }).click();
  const license = page.getByRole('dialog', { name: '我的授权详情', exact: true });
  await license.getByRole('button', { name: '申请换绑', exact: true }).click();
  const request = page.getByRole('dialog', { name: '申请换绑', exact: true });
  await request.getByLabel('申请原因', { exact: true }).fill('更换已损坏的电脑');
  await request.getByRole('button', { name: '提交申请', exact: true }).click();
  await expect(request).toBeHidden();
  await license.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('tab', { name: '我的申请', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: '更换已损坏的电脑' })).toContainText('待商家处理');

  await page.goto('/portal-requests');
  await expect(page.getByRole('heading', { name: '客户申请', exact: true })).toBeVisible();
  await page.getByRole('row').filter({ hasText: '更换已损坏的电脑' }).getByRole('button', { name: '审批', exact: true }).first().click();
  const review = page.getByRole('dialog', { name: '审批客户申请', exact: true });
  await review.getByRole('radio', { name: '批准申请', exact: true }).check();
  await review.getByLabel('审批原因', { exact: true }).fill('已核对设备更换需求');
  await review.getByRole('button', { name: '保存审批', exact: true }).click();
  await expect(review).toBeHidden();
  expect((await page.request.post('/api/client/sessions/heartbeat', { headers: { Authorization: `Bearer ${grant.sessionToken}` } })).ok()).toBe(false);
  const policy = await (await page.request.get(`/api/admin/licenses/${licenseId}/device-policy`)).json();
  expect(policy.usedChanges).toBe(1);
  await page.goto('/portal/requests');
  await expect(page.getByRole('row').filter({ hasText: '更换已损坏的电脑' })).toContainText('已批准');
  await page.reload();
  await expect(page.getByRole('row').filter({ hasText: '更换已损坏的电脑' })).toContainText('已批准');
});
